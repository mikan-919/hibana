import { test, expect } from '@playwright/test';

test('投稿を検証し、作成・編集して再読み込みする', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto('/');
  await expect(page.locator('#post-count')).toHaveText(/\d+ 件/);
  await expect(page.getByRole('heading', { name: '新しい投稿' })).toBeVisible();
  await page.getByRole('button', { name: '投稿を保存', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('タイトルは1〜120文字');
  await page.getByLabel('タイトル', { exact: false }).fill('取り消す入力');
  await page.getByLabel('本文', { exact: false }).fill('取り消す本文');
  await page.getByRole('button', { name: '入力をクリア', exact: true }).press('Enter');
  await expect(page.getByLabel('タイトル', { exact: false })).toHaveValue('');
  await expect(page.getByLabel('本文', { exact: false })).toHaveValue('');
  await expect(page.getByRole('status')).toHaveText('入力をクリアしました');
  await expect(page.getByLabel('タイトル', { exact: false })).toBeFocused();
  const title = `検証用の投稿 ${Date.now()}`;
  const body = '<script>window.hanabiInjected=true</script>\n本文🌸';
  await page.getByLabel('タイトル', { exact: false }).fill(title);
  await page.getByLabel('本文', { exact: false }).fill(body);
  await page.getByRole('button', { name: '投稿を保存', exact: true }).click();
  let post = page.locator('article.post').filter({ hasText: title });
  await expect(post).toBeVisible();
  await expect(post.locator('.post-body')).toHaveText(body);
  await expect(post.locator('script')).toHaveCount(0);
  expect(await page.evaluate(() => window.hanabiInjected)).toBeUndefined();
  await post.getByRole('button').click();
  await expect(page.getByRole('heading', { name: '投稿を編集' })).toBeVisible();
  await page.getByLabel('タイトル', { exact: false }).fill(`${title} 編集済み`);
  await page.getByLabel('本文', { exact: false }).fill('更新した本文');
  await page.getByRole('button', { name: '変更を保存', exact: true }).click();
  post = page.locator('article.post').filter({ hasText: `${title} 編集済み` });
  await expect(post.locator('.post-body')).toHaveText('更新した本文');
  await page.reload();
  await expect(page.locator('article.post').filter({ hasText: `${title} 編集済み` })).toBeVisible();
  expect(errors).toEqual([]);
});
